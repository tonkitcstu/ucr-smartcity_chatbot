#
# **ปุ่มเป็นของข้อความ ไม่ใช่ของใบ** คนที่รู้ว่าประโยคที่เพิ่งเขียนต้องการปุ่มอะไร
# คือคนที่เขียนประโยคนั้น โมเดลติดป้ายมาเอง เราแกะออกก่อนส่งถึงชาวบ้าน
