# เดิมโค้ดเดาเองจากสภาพใบว่าควรมีปุ่มอะไร กลายเป็นสองคนตัดสินเรื่องเดียวกัน
# โดยไม่คุยกัน — โมเดลเขียนคำลา โค้ดแปะปุ่มขอรูปไว้ข้างล่าง / โมเดลบอกว่า
# "กดปุ่มข้างล่างได้เลย" แต่โค้ดเห็นว่าใบมีพิกัดแล้วเลยไม่ส่งปุ่มไป
# **คนที่เห็นความขัดแย้งคือชาวบ้าน** ที่มาเดียวเท่านั้นถึงจะขัดกันเองไม่ได้
_PIN_MARK = "ตำแหน่ง"
_PHOTO_MARK = "รูป"
_MARK = re.compile(r"\s*\[\s*ปุ่ม\s*[:：]\s*([^\]]*)\]")


def _buttons(text: str) -> tuple[str, bool, bool]:
    """แกะป้ายปุ่มออกจากข้อความ คืน (ข้อความที่ชาวบ้านเห็น, ปุ่มตำแหน่ง, ปุ่มรูป)

    ป้ายที่สะกดเพี้ยนไปจากที่สั่งไว้ก็ยังถูกแกะออก **ห้ามให้วงเล็บหลุดถึงชาวบ้าน**
    เขาไม่ได้อยู่ในบทสนทนาเดียวกับเรา เขาเห็นแค่ข้อความจากคนที่ชื่อน้องเมือง
    """
    asks = _MARK.findall(text)
    return (
        _MARK.sub("", text).strip(),
        any(_PIN_MARK in ask for ask in asks),
        any(_PHOTO_MARK in ask for ask in asks),
    )


# ตาข่ายรองสำหรับปุ่มตำแหน่งอย่างเดียว เผื่อโมเดลชวนแล้วลืมติดป้าย
# **ปุ่มกล้องไม่ต้องมีตาข่าย** ในแอปแชทมีปุ่มแนบรูปของมันเองอยู่แล้ว หาไม่เจอก็ยังส่งได้
# แต่ปุ่มส่งตำแหน่งไม่มีทางอื่นเลย และคนแก่คือคนที่ติดตรงนี้มากที่สุด
_PIN_WORDS = ("ตำแหน่ง", "พิกัด", "ปักหมุด")
_BUTTON_WORDS = ("ปุ่ม", "กด")


def _invites_pin(text: str) -> bool:
    return any(word in text for word in _PIN_WORDS) and any(
        word in text for word in _BUTTON_WORDS
    )


def focus(reports: dict) -> tuple[str, str] | None:
    """ตานี้ควรคุยเรื่องไหนต่อ และยังขาดอะไร — คืน (ชื่อเรื่อง, สิ่งที่ขาด)

    เลือกใบที่ขาดมากที่สุดก่อน เท่ากันก็เอาใบที่เขาเล่ามาก่อน
    คืน None แปลว่าทุกใบครบหมดแล้ว ไม่ต้องถามอะไรอีก
    """
    waiting = []

    for topic, report in reports.items():
        goal = next_goal(report)
        if goal is None:
            continue
        waiting.append((_GOAL_URGENCY.get(goal, 0), report.get("_seq", 0), topic, goal))

    if not waiting:
        return None

    _, _, topic, goal = min(waiting)
    return topic, goal


def ready(reports: dict) -> list[str]:
    """ใบที่ครบแล้ว พร้อมย้ายไปที่เก็บถาวร — เรียงตามลำดับที่เขาเล่ามา"""
    done = [(rep.get("_seq", 0), topic) for topic, rep in reports.items() if is_complete(rep)]
    return [topic for _, topic in sorted(done)]


def current_topic(reports: dict) -> str:
    """ใบที่ของซึ่งไม่มีเลขติดมาด้วยควรลง

    ของจากปุ่ม (พิกัด รูป) ไม่มีทางรู้ว่าเป็นของเรื่องไหน — ให้ลงใบที่กำลังคุยอยู่
    ยังไม่มีใบไหนเลยก็เปิดใบที่ 1 ให้
    """
    spot = focus(reports)
    if spot:
        return spot[0]
    if reports:
        return max(reports, key=lambda topic: reports[topic].get("_seq", 0))
    return "1"


