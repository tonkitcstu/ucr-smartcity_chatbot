# หางที่โมเดลชอบต่อท้าย notes หลังตาที่มีรูปส่งมา — "… ส่งรูปมาให้ดู 2 รูป"
# มันถอดความมาจาก marker [ระบบ: ผู้ใช้ส่งรูปมาให้ 2 รูป …] ซึ่งเป็นเสียงของระบบ
# ไม่ใช่คำที่ใครพูด กฎห้ามลอกในพรอมป์ทจับได้แค่ตัวอักษรตรง ๆ ไม่ได้จับการเรียบเรียงใหม่
# ปล่อยไว้ทีมออกแบบจะอ่านเจอประโยคที่ไม่มีใครพูดติดท้ายทุกใบที่มีรูป
_PHOTO_ECHO = re.compile(
    r"[\s,]*(?:และ|แล้ว)?\s*(?:ได้)?(?:ส่ง|แนบ|ถ่าย)(?:รูป|ภาพ)"
    r"[^\n]{0,15}?\d+\s*(?:รูป|ภาพ)[^\n]{0,15}$"
)


def _drop_photo_echo(notes: str) -> str:
    """ตัดหางที่มาจาก marker ออกจากเรื่องเล่า

    **ตัดสั้นกว่าครึ่ง = จับผิดตัว** คืนของเดิมไป เรื่องที่เขาอุตส่าห์เล่ามา
    สำคัญกว่าประโยคเกินหนึ่งประโยค ตัวกรองนี้ห้ามเป็นเหตุให้ใครเสียเรื่องของตัวเอง
    """
    trimmed = _PHOTO_ECHO.sub("", notes).strip(" ,")
    return trimmed if len(trimmed) * 2 >= len(notes) else notes


def _sanitize(arguments: dict) -> dict:
    """เจอค่านอกรายการ ทิ้งเฉพาะค่านั้น ไม่ทิ้งทั้งใบ

    วันหนึ่งโมเดลจะส่ง "urgent" มาแทน "high" แน่ ๆ ตอนนั้นเราต้องยังได้เรื่อง
    ที่ชาวบ้านอุตส่าห์เล่ามาเก็บไว้ **ห้ามให้ค่าผิดช่องเดียวฆ่าทั้งรายงาน**
    """
    clean = {}

    for field, value in arguments.items():
        if field == "notes" and value:
            clean[field] = _drop_photo_echo(str(value))
        elif field in _VOCAB:
            if value in _VOCAB[field]:
                clean[field] = value
        elif field in _LIST_VOCAB:
            # ซ้ำได้ แต่ลำดับต้องคงเดิม เพราะตัวแรกของ categories คือเรื่องหลัก
            kept = list(dict.fromkeys(
                v for v in value or [] if v in _LIST_VOCAB[field]
            ))
            if field == "categories" and len(kept) > 1:
                # other คือทางออกตอนไม่มีหัวข้อไหนตรงเลย ไม่ใช่คำขยายของหัวข้ออื่น
                # ปล่อยให้ติดคู่กันเมื่อไหร่ ตัวกรอง "อื่น ๆ" จะกวาดมาทั้งแผนที่
                kept = [v for v in kept if v != "other"]
            if kept:
                clean[field] = kept
        else:
            clean[field] = value

    return clean


def _home_said(message: str, homes: list[str]) -> str | None:
    """หาชื่อชุมชนในสิ่งที่เขาพิมพ์มา คืน None ถ้าไม่เจอ

    **ใช้ได้เฉพาะตาที่เราเพิ่งถามเรื่องชุมชนไปเท่านั้น** ห้ามเอาไปไล่จับทุกข้อความ
    เพราะชื่อชุมชนหลายอันเป็นชื่อสถานที่ที่คนพูดถึงตามปกติ — "เดินไปตลาดหลักสี่
    ไม่ได้เลย" จะกลายเป็นว่าเขาอยู่ชุมชนตลาดหลักสี่ ทั้งที่เขาแค่เดินไปตลาด
    จับเฉพาะตาที่เป็นคำตอบของคำถามเรา มันไม่ใช่การเดา มันคือการอ่านคำตอบ

    ที่ต้องจับเองแทนที่จะรอโมเดลส่ง community มาให้: ตาที่เขาตอบคือตาที่ใบครบแล้ว
    ระบบสั่งโมเดลว่า "ปิดท้ายได้ ห้ามถามอะไรอีก" มันจึงพิมพ์ว่ารับทราบแล้วจบ
    **โดยไม่เรียกเครื่องมือ** เจอมาแล้วจริง ชื่อชุมชนที่เขาอุตส่าห์พิมพ์มาหายไปเฉย ๆ
    """
    text = " ".join(message.split())

    # เทียบชื่อยาวก่อน กันชื่อที่เป็นส่วนหนึ่งของอีกชื่อแย่งกันจับ
    # ("ชุมชนเทวสุนทร" อยู่ใน "ชุมชนสามัคคีเทวสุนทร")
    for name in sorted(homes, key=len, reverse=True):
        if name in text or name.removeprefix("ชุมชน").strip() in text:
            return name

    return None


def _slot_of(sent, reports: dict) -> str:
    """ใบที่ของชุดนี้ควรลง — คืนเลขใบเป็นข้อความ

    ไม่ส่งเลขมา หรือส่งมาเป็นอย่างอื่นที่ไม่ใช่เลข = ยังเป็นเรื่องเดิมที่คุยค้างอยู่
    ส่งเลขที่ยังไม่มี = เปิดใบใหม่ แต่เปิดพร้อมกันได้ไม่เกิน MAX_OPEN_REPORTS
    เกินนั้นถือว่ามันหลง ให้ลงใบที่กำลังคุยอยู่แทน — ใบล้นเป็นสิบใบไม่ช่วยใครเลย
    """
    try:
        no = int(sent)
    except (TypeError, ValueError):
        return current_topic(reports)

    slot = str(no)
    if slot in reports:
        return slot

    if len(reports) >= MAX_OPEN_REPORTS:
        return current_topic(reports)

    return slot


def _allowed(arguments: dict, report: dict) -> dict:
    """กรองสิ่งที่โมเดลส่งมา ก่อนให้เขียนลงใบ

    ถ้าตำแหน่งมาจากปุ่มแชร์แล้ว ห้ามโมเดลเขียนทับ — เคยเจอมันทับ
    "ซอยเพชรเกษม 63 แขวงหลักสอง" ด้วยคำว่า "ตำแหน่งที่ผู้ใช้แชร์มา" ซึ่งไม่มีข้อมูลอะไรเลย
    """
    if not report.get("_location_locked"):
        return arguments
    return {k: v for k, v in arguments.items() if k != "location_text"}


HEADLINE_CHARS = 40


def _headline(notes: str) -> str:
    """พาดหัวจากเรื่องที่เขาเล่า — ถอยมาจบที่ช่องว่าง ไม่ตัดคาคำ

    ไทยเขียนติดกันยาว ๆ ช่องว่างมาห่างกันมาก การยอมสั้นลงเยอะเพื่อให้จบคำ
    จึงคุ้มกว่าที่คิด **ตัดคาคำแย่กว่าตัดสั้น** เว้นแต่สั้นจนไม่เหลือความหมาย
    (ต่ำกว่าหนึ่งในสามของโควตา) อันนั้นตัดตรง ๆ ดีกว่า
    """
    text = " ".join(notes.split())
    if len(text) <= HEADLINE_CHARS:
        return text

    cut = text[:HEADLINE_CHARS]
    space = cut.rfind(" ")
    return cut[:space] if space > HEADLINE_CHARS // 3 else cut


def public(report: dict) -> dict:
    """ตัดช่องที่เราใช้นับภายในออก ขึ้นต้นด้วย _ = ไม่ลง DB ไม่โผล่ออก API

    เป็นคอขวดเดียวก่อนลงที่เก็บถาวร ทั้งทางปิดใบปกติและทางที่ sweeper เก็บให้
    จึงเป็นที่ที่เติม `title` ให้เอง — โมเดลมักลืมช่องนี้ แล้วของที่ตามมาทีหลัง
    พังต่อกันเป็นทอด: แดชบอร์ดขึ้นเรื่องเล่าท่อนกลางแทนพาดหัว และรูปที่ส่งตามมา
    หลังปิดใบได้คำบรรยายเป็น null เพราะ `clients/storage.add_image` ใช้ title
    เป็นคำบรรยาย **พาดหัวเป็นของที่เราเขียนให้คนอ่าน ไม่ใช่ของที่ต้องไปถามเจ้าของเรื่อง**
    """
    clean = {k: v for k, v in report.items() if not k.startswith("_")}

    if not clean.get("title") and clean.get("notes"):
        clean["title"] = _headline(str(clean["notes"]))

    return clean


def _with_markers(message: str, latitude, longitude, photos: int) -> str:
    """รูป/พิกัดไม่เข้าโมเดล — ยัด marker บอกให้รู้แทน ประหยัดและไม่หลุดข้อมูลส่วนตัว"""
    markers = []

    if latitude is not None and longitude is not None:
        markers.append(f"[ระบบ: ผู้ใช้แชร์ตำแหน่งมาแล้ว {latitude}, {longitude}]")

    if photos:
        # บอกจำนวนจริง เขากดส่งทีเดียวหลายใบ พูดว่า "1 รูป" จะกลายเป็นไม่ได้ฟังเขา
        markers.append(
            f"[ระบบ: ผู้ใช้ส่งรูปมาให้ {photos} รูป เก็บไว้ให้แล้ว คุณดูรูปไม่ได้]"
        )

    return " ".join(markers + [message]).strip()
