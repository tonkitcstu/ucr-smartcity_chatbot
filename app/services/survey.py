def next_goal(report: dict) -> str | None:
    """ใบนี้ยังต้องถามอะไรต่อ — คืน None แปลว่าพอแล้ว ปิดใบได้

    ตำแหน่งกับรูปไม่ใช่ช่องบังคับ แต่ปลายทางคือหมุดบนแผนที่ เลยขอไปเรื่อยจนกว่า
    **AI จะบอกเองว่าเขาปฏิเสธแล้ว** (no_location / no_photo)
    เมื่อก่อนตรงนี้เป็นโควตานับจำนวนครั้ง ซึ่งนับได้แต่จำนวน ไม่รู้ว่าเขาตอบว่าอะไร
    ถามไปสองหนโดยที่เขายังไม่ทันปฏิเสธก็เลิกขอ ส่วนคนที่ปฏิเสธตั้งแต่หนแรกก็ยังโดนถามอีก

    รูปขอทีหลังตำแหน่ง เพราะตำแหน่งมีค่ากว่า (ไม่มีพิกัด = ไม่ขึ้นหมุด)
    ถ้ายิงขอพร้อมกันจะแย่งความสนใจกันเอง แล้วอาจไม่ได้สักอย่าง

    ผลกระทบขอทีหลังตำแหน่งแต่ก่อนรูป เพราะรูปเคยเป็นด่านสุดท้าย พอรูปมาถึงใบก็ปิดทันที
    แม้ยังไม่มีใครถามสักคำว่าเรื่องนี้ทำอะไรกับชีวิตเขา — เกิดขึ้นแล้วจริงในใบที่ 1
    """
    left = missing(report)
    if left:
        return left[0]

    if not has_location(report) and not report.get("no_location"):
        return "location"

    if impact_open(report):
        return "impact"

    if not has_image(report) and not report.get("no_photo"):
        return "photo"

    if home_open(report):
        return "community"

    return None


def impact_open(report: dict) -> bool:
    """ยังต้องถามเรื่องผลกระทบอยู่ไหม

    **ถามได้ครั้งเดียว** พอเขาพิมพ์ตอบกลับมาแล้วก็เลิกถาม ไม่ว่าคำตอบจะใช้ได้หรือไม่
    ถามซ้ำคือทวง แล้วใบที่ค้างรอคำตอบที่ไม่มีวันมาจะหมดอายุหายไปทั้งใบ
    **ใบที่ไม่มีผลกระทบยังดีกว่าใบที่ไม่มี**

    ที่ต้องมีด่านนี้เพราะที่เหลือทั้งใบเป็นของที่เซ็นเซอร์เก็บแทนได้หมด — พิกัด ประเภท
    เวลา ความถี่ สิ่งเดียวที่เก็บแทนไม่ได้คือคำที่เขาใช้เล่าว่ามันทำให้เขาต้องทำอะไร
    """
    return not report.get("affect_desc") and not report.get("_impact_done")


def home_open(report: dict) -> bool:
    """ยังต้องถามว่าเขาอยู่ชุมชนไหนอยู่ไหม

    **ถามได้ครั้งเดียว และเป็นคำถามสุดท้ายเสมอ** — มันไม่ใช่เรื่องที่เขาเดินมาเล่า
    ถามก่อนได้เรื่องของเขาครบคือเอาแบบฟอร์มไปขวางคนที่กำลังจะเล่าอะไรให้ฟัง

    `_home_needed` ปักโดย _turn ตามความจริงใน users ตอนนั้น และถูกถอดทันที
    ที่เขาบอกมา — ไม่ใช่ของที่เดาจากในใบได้ เพราะชุมชนเป็นของตัวคน ไม่ใช่ของใบ

    เคยปล่อยให้เป็นแค่บรรทัดแนะนำในพรอมป์ทโดยไม่มีด่านตรงนี้ ผลคือ**ไม่เคยถูกถาม
    เลยสักครั้ง** เพราะ _status() สั่งเป้าหมายรายตาแรงกว่า คำถามที่ไม่มีน้ำหนัก
    แพ้ทุกครั้ง แล้วตาราง users ก็ว่างเปล่า = broadcast ไม่มีใครให้ทัก
    """
    return bool(report.get("_home_needed")) and not report.get("_home_asked")


def is_complete(report: dict) -> bool:
    return next_goal(report) is None


